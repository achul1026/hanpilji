class ApiError(RuntimeError):
    pass


def get(url, tries=4):
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "hanpilji-collector/0.1"})
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code < 500 or i == tries - 1:
                return e.read()
        except OSError:
            if i == tries - 1:
                raise
        time.sleep(2 ** (i + 1))


def parse(data):
    """(도형 목록, 전체 건수). 결과 없음(NOT_FOUND)은 빈 목록."""
    text = data.decode("utf-8-sig").strip()
    try:
        resp = json.loads(text)["response"]
    except (ValueError, KeyError, TypeError):
        raise ApiError(f"알 수 없는 응답: {text[:200]}") from None
    status = str(resp.get("status", "")).upper()
    if status == "NOT_FOUND":
        return [], 0
    if status != "OK":
        err = resp.get("error") or {}
        raise ApiError(f"{err.get('code', status)} {err.get('text', '')}".strip())
    feats = ((resp.get("result") or {}).get("featureCollection") or {}).get("features") or []
    try:
        total = int(str((resp.get("record") or {}).get("total") or len(feats)))
    except ValueError:
        total = len(feats)
    return feats, total


def fatal(e):
    s = str(e).upper()
    return any(w in s for w in ("KEY", "DOMAIN", "LIMIT", "EXCEED", "인증키", "도메인", "한도", "초과"))


def fetch_all(key, domain, layer, **filt):
    feats, page, calls = [], 1, 0
    while True:
        q = urllib.parse.urlencode({"service": "data", "request": "GetFeature", "version": "2.0",
                                    "data": layer, "key": key, "domain": domain, "format": "json",
                                    "crs": "EPSG:4326", "geometry": "true", "attribute": "true",
                                    "size": PAGE_SIZE, "page": page, **filt})
        part, total = parse(get(f"{BASE}?{q}"))
        calls += 1
        feats += part
        if not part or len(feats) >= total:
            return feats, calls
        page += 1
        time.sleep(0.1)


def save(path, obj):
    tmp = path.with_suffix(".part")
    tmp.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    tmp.replace(path)


def tiles():
    x0, y0, x1, y1 = BBOX
    nx, ny = round((x1 - x0) / STEP_X + 0.4999), round((y1 - y0) / STEP_Y + 0.4999)
    for j in range(ny):
        for i in range(nx):
            a, b = x0 + i * STEP_X, y0 + j * STEP_Y
            yield f"{j:02d}_{i:02d}", (round(a, 6), round(b, 6), round(a + STEP_X, 6), round(b + STEP_Y, 6))


def main():
    key = os.environ.get("VWORLD_KEY", "").strip() or getpass.getpass("V-World 인증키(입력해도 화면에 안 보임): ").strip()
    if not key:
        sys.exit("인증키가 없음")
    domain = os.environ.get("VWORLD_DOMAIN", "http://localhost")
    for kind in LAYERS:
        (OUT / kind).mkdir(parents=True, exist_ok=True)
    (OUT / "pnu").mkdir(parents=True, exist_ok=True)
    grid = list(tiles())
    calls = failed = 0
    stop = False

    def run(path, layer, label, **filt):
        nonlocal calls, failed, stop
        if path.exists():
            return None
        try:
            feats, n = fetch_all(key, domain, layer, **filt)
        except Exception as e:
            failed += 1
            print(f"실패 {label}: {str(e).replace(key, '***')}", file=sys.stderr)
            if fatal(e):
                print("인증키 · 도메인 · 하루 한도 문제라 멈춤. 해결한 뒤 다시 돌리면 이어 받음.", file=sys.stderr)
                stop = True
            return None
        calls += n
        save(path, {"layer": layer, "filter": filt, "features": feats})
        time.sleep(0.1)
        return feats

    for k, (tid, box) in enumerate(grid, 1):
        for kind, layer in LAYERS.items():
            feats = run(OUT / kind / f"{tid}.json", layer, f"{kind} 칸 {tid}",
                        geomFilter="BOX({},{},{},{})".format(*box))
            if feats is not None:
                print(f"[{k}/{len(grid)}] 칸 {tid} {'필지' if kind == 'parcel' else '건물'} {len(feats)}개")
            if stop:
                break
        if stop:
            break

    # 칸에서 안 잡힌 한필지 필지는 필지번호로 직접
    if not stop:
        seen = set()
        for p in (OUT / "parcel").glob("*.json"):
            for f in json.loads(p.read_text(encoding="utf-8"))["features"]:
                seen.add(str((f.get("properties") or {}).get("pnu", "")))
        miss = [p for p in PNUS if p not in seen and not (OUT / "pnu" / f"{p}.json").exists()]
        if miss:
            print(f"\n칸에서 안 잡힌 필지 {len(miss)}개를 필지번호로 받음")
        for i, pnu in enumerate(miss, 1):
            feats = run(OUT / "pnu" / f"{pnu}.json", LAYERS["parcel"], f"필지 {pnu}", attrFilter=f"pnu:=:{pnu}")
            if feats is not None:
                print(f"[{i}/{len(miss)}] {pnu} {len(feats)}개")
            if stop:
                break

    have = sum(1 for _ in OUT.rglob("*.json"))
    print(f"\n파일 {have}개 · 이번 호출 {calls}회 · 실패 {failed}개")
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(OUT.rglob("*.json")):
            z.write(p, p.relative_to(OUT))
    print(f"→ {ZIP}  ({ZIP.stat().st_size // 1024} KB) 이 파일을 돌려주세요")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
